def tools_in(stage):
    return sorted((t for t in TOOLS if t["stage"] == stage), key=lambda t: t["order"])


def _fill(value):
    value = (value or "").strip()
    return value if value else UNKNOWN


def build_prompt(tool, service, values):
    """상황 블록 + 도구 문장 + 공통 지킬 것. 빈 값은 '미정'. 문장이 없으면 None."""
    if tool["template"] is None:
        return None
    context = CONTEXT_BLOCK.format(**{k: _fill(service.get(k)) for k in
                                      ("me", "name", "customer", "problem", "solution", "team", "goal", "rules")})
    body = tool["template"].format(**{f[0]: _fill(values.get(f[0])) for f in tool["fields"]})
    return f"{context}\n\n{body}\n\n{COMMON_RULES}"


